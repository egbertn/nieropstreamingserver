    internal static string Get(HttpRequest request, string code, params object?[] arguments)
    {
        var firstLanguage = request.Headers.AcceptLanguage.ToString().Split(',')[0].Trim();
        var language = firstLanguage.StartsWith("nl", StringComparison.OrdinalIgnoreCase) ? "nl" : "en";
        var message = Messages[$"{language}/{code}"];
        return arguments.Length == 0 ? message : string.Format(message, arguments);
    }
